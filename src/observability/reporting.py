def _recovery_status_label(status: str) -> str:
    return {"full": "FULL", "partial": "PARTIAL", "none": "NOT RECOVERED", "unknown": "N/A"}.get(status, status)


def _gate_status(ok: bool | None) -> str:
    if ok is True:
        return "PASS"
    if ok is False:
        return "FAIL"
    return "—"


def _demo_block(label: str, entry: dict[str, Any] | None) -> list[str]:
    lines: list[str] = []
    if entry is None:
        lines.append(f"_No {label} case available — answers files required._\n")
        return lines
    lines.append(f"**ID**: `{entry.get('id')}`  **Type**: `{entry.get('question_type')}`\n")
    lines.append(f"> **Question**: {entry.get('question')}\n")
    gt = (entry.get("ground_truth_excerpt") or "")
    if gt:
        lines.append(f"> **Ground truth**: {gt}\n")
    lines.append("| State | Token F1 | Judge score | Retrieval hit |")
    lines.append("|---|---|---|---|")
    lines.append(
        f"| Baseline  | {_fmt(entry.get('baseline_token_f1'))} "
        f"| {entry.get('baseline_judge_score') or '—'} | — |"
    )
    lines.append(
        f"| Corrupted | {_fmt(entry.get('corrupted_token_f1'))} "
        f"| {entry.get('corrupted_judge_score') or '—'} "
        f"| {entry.get('corrupted_retrieval_hit')} |"
    )
    lines.append(
        f"| Repaired  | {_fmt(entry.get('repaired_token_f1'))} "
        f"| {entry.get('repaired_judge_score') or '—'} "
        f"| {entry.get('repaired_retrieval_hit')} |"
    )
    lines.append("")
    if entry.get("corrupted_answer_excerpt"):
        lines.append(f"**Corrupted answer**: {entry.get('corrupted_answer_excerpt')}\n")
    if entry.get("repaired_answer_excerpt"):
        lines.append(f"**Repaired answer**: {entry.get('repaired_answer_excerpt')}\n")
    return lines


def generate_cp6_report(
    report_path,
    recovery: dict[str, Any],
) -> None:
    """Checkpoint 6: 3-state comparison report — baseline / corrupted / repaired."""
    lines: list[str] = []
    lines.append("# Checkpoint 6 — Recovery Comparison Report\n")
    lines.append(
        "> So sánh ba trạng thái baseline / corrupted / repaired trên "
        "metric, quality gate, freshness và từng câu trả lời thực tế. "
        "Ghi rõ recovery chưa hoàn toàn và giới hạn kết luận.\n"
    )

    summary = recovery.get("recovery_summary", {})

    # --- 1. Metric 3-state delta table ---
    lines.append("## 1. Metric — 3-State Delta\n")
    mr = recovery.get("metric_recovery", {})
    metrics_available = summary.get("metrics_available", False)
    if not metrics_available:
        lines.append(
            "> _Metric files not found — run `uv run python script/run_corruption_flow.py` "
            "to generate all three metric JSON files. Recovery verdicts show as N/A._\n"
        )
    lines.append("| Metric | Baseline | Corrupted | Repaired | Δ corrupt | Δ repair | Δ recover | Status |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for key, v in mr.items():
        b = _fmt(v.get("baseline"))
        c = _fmt(v.get("corrupted"))
        r = _fmt(v.get("repaired"))
        dc = f"{v['delta_corrupt']:+.4f}" if v.get("delta_corrupt") is not None else "—"
        dr = f"{v['delta_repair']:+.4f}" if v.get("delta_repair") is not None else "—"
        drec = f"{v['delta_recover']:+.4f}" if v.get("delta_recover") is not None else "—"
        status = _recovery_status_label(v.get("recovery_status", "unknown"))
        lines.append(f"| {key} | {b} | {c} | {r} | {dc} | {dr} | {drec} | {status} |")
    lines.append("")

    if not metrics_available:
        lines.append("**Overall metric recovery**: N/A — metric files required.\n")
    else:
        full = summary.get("full_recovered_metrics", [])
        partial = summary.get("partial_recovered_metrics", [])
        none_ = summary.get("not_recovered_metrics", [])
        lines.append(f"- **Fully recovered** (|Δ repair| < 0.02): {', '.join(f'`{m}`' for m in full) or 'none'}")
        lines.append(f"- **Partially recovered** (improved but not baseline): {', '.join(f'`{m}`' for m in partial) or 'none'}")
        lines.append(f"- **Not recovered**: {', '.join(f'`{m}`' for m in none_) or 'none'}")
    lines.append("")

    # --- 2. Quality gate 3-state comparison ---
    lines.append("## 2. Quality Gates — 3-State Comparison\n")
    qr = recovery.get("quality_recovery", [])
    lines.append("| Check | Baseline | Corrupted | Repaired | Gate recovery |")
    lines.append("|---|---|---|---|---|")
    for g in qr:
        b_s = _gate_status(g.get("baseline"))
        c_s = _gate_status(g.get("corrupted"))
        r_s = _gate_status(g.get("repaired"))
        rec = g.get("gate_recovery", "unknown").replace("_", " ").upper()
        lines.append(f"| `{g['check']}` | {b_s} | {c_s} | {r_s} | {rec} |")
    lines.append("")
    lines.append(
        f"**Summary**: "
        f"{summary.get('gate_recovered', '—')} gate(s) recovered · "
        f"{summary.get('gate_still_failing', '—')} still failing · "
        f"{summary.get('gate_stable', '—')} unchanged\n"
    )

    # --- 3. Freshness 3-state ---
    lines.append("## 3. Freshness — 3-State\n")
    fr = recovery.get("freshness_recovery", {})
    lines.append("| State | is_fresh | stale_ratio |")
    lines.append("|---|---|---|")
    lines.append(
        f"| Baseline  | {fr.get('baseline_fresh')} | {_fmt(fr.get('baseline_stale_ratio'))} |"
    )
    lines.append(
        f"| Corrupted | {fr.get('corrupted_fresh')} | {_fmt(fr.get('corrupted_stale_ratio'))} |"
    )
    lines.append(
        f"| Repaired  | {fr.get('repaired_fresh')} | {_fmt(fr.get('repaired_stale_ratio'))} |"
    )
    freshness_ok = fr.get("freshness_recovered", False)
    lines.append(
        f"\n**Freshness recovery**: {'YES — repaired dataset is fresh again.' if freshness_ok else 'NO — still stale after repair.'}\n"
    )

    # --- 4. Per-answer recovery breakdown ---
    lines.append("## 4. Per-Answer Recovery Breakdown\n")
    ans_available = summary.get("answers_available", False)
    label_counts = summary.get("answer_label_counts", {})
    if not ans_available:
        lines.append("_Answer files not available — run the full corruption flow._\n")
    else:
        total = sum(label_counts.values())
        lines.append("| Recovery label | Count | % of questions | Meaning |")
        lines.append("|---|---|---|---|")
        labels_doc = {
            "recovered": "Corrupted broke it, repair fixed it",
            "consistent_hit": "Correct in both corrupted and repaired states",
            "consistent_miss": "Still wrong after repair — unresolved gap",
            "newly_broken": "Repair unexpectedly broke a previously-correct answer",
        }
        for label, doc in labels_doc.items():
            count = label_counts.get(label, 0)
            pct = f"{count / total * 100:.0f}%" if total else "—"
            lines.append(f"| `{label}` | {count} | {pct} | {doc} |")
        lines.append("")

        # Recovery completeness verdict from answers
        recovered_n = label_counts.get("recovered", 0)
        miss_n = label_counts.get("consistent_miss", 0)
        if miss_n == 0:
            lines.append("**Answer-level verdict**: All corrupted misses were recovered.\n")
        else:
            lines.append(
                f"**Answer-level verdict**: {miss_n} question(s) still miss after repair — "
                f"recovery is incomplete at the answer level.\n"
            )

    # --- 5. Representative demo cases ---
    lines.append("## 5. Representative Demo Cases\n")
    demo = recovery.get("demo_cases", {})

